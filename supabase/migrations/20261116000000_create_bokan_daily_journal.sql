create schema if not exists private;
revoke all on schema private from public, anon;
grant usage on schema private to authenticated;

create table if not exists public.journal_user_access (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('admin','data_entry','viewer')),
  is_active boolean not null default true,
  invited_email text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.journal_entries (
  id uuid primary key default gen_random_uuid(),
  entry_number bigint generated by default as identity unique,
  business_day date not null default ((now() at time zone 'Africa/Addis_Ababa')::date),
  transaction_date date not null,
  transaction_type text not null check (transaction_type in ('Sales (Cash)','Sales (Credit)','Purchase','Delivery','Expense','Transfer')),
  company_entity text not null,
  reference_no text,
  party_name text not null,
  product_item text not null,
  location_from text,
  location_to text,
  site_details text,
  vehicle_type text,
  driver_name text,
  quantity numeric(14,3) not null check (quantity > 0),
  unit_price numeric(14,2) check (unit_price is null or unit_price >= 0),
  total_amount numeric(16,2) generated always as (round(quantity * coalesce(unit_price,0),2)) stored,
  payment_method text,
  handler text,
  remarks text,
  created_by uuid not null references auth.users(id),
  updated_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists journal_entries_business_day_idx on public.journal_entries (business_day, created_at desc);
create index if not exists journal_entries_transaction_date_idx on public.journal_entries (transaction_date desc);
create index if not exists journal_entries_company_idx on public.journal_entries (company_entity);
create index if not exists journal_entries_party_idx on public.journal_entries (party_name);

create or replace function private.journal_user_role()
returns text language sql stable security definer set search_path = pg_catalog
as $$
  select ua.role from public.journal_user_access ua
  where ua.user_id = auth.uid() and ua.is_active = true limit 1
$$;
revoke all on function private.journal_user_role() from public, anon;
grant execute on function private.journal_user_role() to authenticated;

create or replace function public.journal_set_updated_at()
returns trigger language plpgsql set search_path = pg_catalog
as $$ begin new.updated_at := now(); new.updated_by := auth.uid(); return new; end; $$;
drop trigger if exists journal_entries_set_updated_at on public.journal_entries;
create trigger journal_entries_set_updated_at before update on public.journal_entries
for each row execute function public.journal_set_updated_at();

alter table public.journal_user_access enable row level security;
alter table public.journal_entries enable row level security;
drop policy if exists journal_access_select on public.journal_user_access;
create policy journal_access_select on public.journal_user_access for select to authenticated
using (user_id = (select auth.uid()) or private.journal_user_role() = 'admin');
drop policy if exists journal_access_admin_insert on public.journal_user_access;
create policy journal_access_admin_insert on public.journal_user_access for insert to authenticated
with check (private.journal_user_role() = 'admin');
drop policy if exists journal_access_admin_update on public.journal_user_access;
create policy journal_access_admin_update on public.journal_user_access for update to authenticated
using (private.journal_user_role() = 'admin') with check (private.journal_user_role() = 'admin');
drop policy if exists journal_entries_select on public.journal_entries;
create policy journal_entries_select on public.journal_entries for select to authenticated
using (private.journal_user_role() in ('admin','data_entry','viewer'));
drop policy if exists journal_entries_insert on public.journal_entries;
create policy journal_entries_insert on public.journal_entries for insert to authenticated
with check (private.journal_user_role() in ('admin','data_entry') and created_by = (select auth.uid()));
drop policy if exists journal_entries_update on public.journal_entries;
create policy journal_entries_update on public.journal_entries for update to authenticated
using (private.journal_user_role() = 'admin' or (private.journal_user_role() = 'data_entry' and business_day = (now() at time zone 'Africa/Addis_Ababa')::date and (now() at time zone 'Africa/Addis_Ababa')::time < time '18:00'))
with check (private.journal_user_role() = 'admin' or (private.journal_user_role() = 'data_entry' and business_day = (now() at time zone 'Africa/Addis_Ababa')::date and (now() at time zone 'Africa/Addis_Ababa')::time < time '18:00'));
grant select on public.journal_user_access to authenticated;
grant insert, update on public.journal_user_access to authenticated;
grant select, insert, update on public.journal_entries to authenticated;
grant usage, select on sequence public.journal_entries_entry_number_seq to authenticated;

