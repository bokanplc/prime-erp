-- Draft schema for independent BOKAN Sales CRM. NOT APPLIED to a Supabase project.
-- Review and convert into migration files after the separate CRM Supabase project is created.

create extension if not exists pgcrypto;

create table public.crm_organizations (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  created_at timestamptz not null default now()
);

create table public.crm_memberships (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.crm_organizations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null check (role in ('owner','sales_manager','supervisor','junior_sales','senior_sales')),
  team_name text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (organization_id,user_id)
);

create table public.crm_leads (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.crm_organizations(id) on delete cascade,
  customer_name text not null,
  contact_name text,
  phone text,
  address text,
  tin text,
  source text,
  product_interest text,
  stage text not null default 'New Lead' check (stage in ('New Lead','Contacted','Quoted','Negotiating','Closed Won','Closed Lost')),
  priority text not null default 'Normal' check (priority in ('Normal','High','Urgent')),
  owner_user_id uuid references auth.users(id),
  next_follow_up timestamptz,
  notes text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.crm_call_logs (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.crm_organizations(id) on delete cascade,
  lead_id uuid references public.crm_leads(id) on delete set null,
  rep_user_id uuid references auth.users(id),
  outcome text not null,
  callback_at timestamptz,
  notes text,
  created_at timestamptz not null default now()
);

create table public.crm_field_visits (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.crm_organizations(id) on delete cascade,
  lead_id uuid references public.crm_leads(id) on delete set null,
  rep_user_id uuid references auth.users(id),
  visit_at timestamptz not null,
  outcome text,
  commitments text,
  follow_up_at timestamptz,
  notes text,
  created_at timestamptz not null default now()
);

create table public.crm_tasks (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.crm_organizations(id) on delete cascade,
  category text not null,
  task_type text not null check (task_type in ('cold_call','follow_up','field_visit','lead_qualification','quote','proforma_request','other')),
  assigned_user_id uuid references auth.users(id),
  assigned_by uuid references auth.users(id),
  due_at timestamptz,
  priority text not null default 'Normal' check (priority in ('Normal','High','Urgent')),
  status text not null default 'Pending' check (status in ('Pending','In Progress','Completed','Cancelled')),
  description text not null,
  completion_notes text,
  completed_at timestamptz,
  created_at timestamptz not null default now()
);

create table public.crm_proforma_requests (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.crm_organizations(id) on delete cascade,
  request_number bigint generated by default as identity,
  company_key text not null,
  customer_name text not null,
  customer_tin text,
  customer_address text not null,
  customer_phone text not null,
  delivery_lead_time text,
  vat_mode text,
  vat_percent numeric(6,3),
  discount_percent numeric(6,3),
  request_notes text,
  requester_user_id uuid references auth.users(id),
  assigned_maker_user_id uuid references auth.users(id),
  status text not null default 'Submitted' check (status in ('Submitted','In Review','Needs Information','In Progress','Completed','Cancelled')),
  deadline date,
  completed_proforma_id uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz,
  unique (organization_id,request_number)
);

create table public.crm_proforma_request_items (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references public.crm_proforma_requests(id) on delete cascade,
  description text not null,
  specification text,
  quantity numeric(14,3) not null check (quantity > 0),
  unit_price numeric(14,2),
  display_order integer not null default 0
);

create table public.crm_daily_submissions (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.crm_organizations(id) on delete cascade,
  user_id uuid not null references auth.users(id),
  report_date date not null,
  summary text,
  status text not null default 'Submitted' check (status in ('Draft','Submitted','Approved','Returned')),
  supervisor_user_id uuid references auth.users(id),
  review_notes text,
  submitted_at timestamptz,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  unique (organization_id,user_id,report_date)
);

create table public.crm_audit_log (
  id bigint generated always as identity primary key,
  organization_id uuid not null references public.crm_organizations(id) on delete cascade,
  actor_user_id uuid references auth.users(id),
  entity_type text not null,
  entity_id uuid not null,
  action text not null,
  before_data jsonb,
  after_data jsonb,
  created_at timestamptz not null default now()
);

create index crm_leads_stage_idx on public.crm_leads(organization_id,stage);
create index crm_leads_followup_idx on public.crm_leads(organization_id,next_follow_up);
create index crm_tasks_due_idx on public.crm_tasks(organization_id,due_at,status);
create index crm_proforma_requests_status_idx on public.crm_proforma_requests(organization_id,status,deadline);
create index crm_calls_rep_date_idx on public.crm_call_logs(organization_id,rep_user_id,created_at);
create index crm_visits_rep_date_idx on public.crm_field_visits(organization_id,rep_user_id,visit_at);

-- RLS enabled. Policies are intentionally not included in this draft until role/team
-- access is reviewed and the exact organization-membership permission model is tested.
alter table public.crm_organizations enable row level security;
alter table public.crm_memberships enable row level security;
alter table public.crm_leads enable row level security;
alter table public.crm_call_logs enable row level security;
alter table public.crm_field_visits enable row level security;
alter table public.crm_tasks enable row level security;
alter table public.crm_proforma_requests enable row level security;
alter table public.crm_proforma_request_items enable row level security;
alter table public.crm_daily_submissions enable row level security;
alter table public.crm_audit_log enable row level security;

-- Security-sensitive deployment checklist:
-- * Organization-membership SELECT policy and admin-only membership mutation.
-- * Team-scoped read/write policies for supervisors.
-- * Junior sales: own leads/calls/tasks/submissions and proforma request create/read.
-- * Senior sales: assigned maker requests and proforma creation permissions only.
-- * Managers/owners: org-wide dashboards, task assignment, approval/audit access.
-- * Proforma issuance/finalization requires server-side authorization.
-- * Audit log inserts are server-controlled and immutable to ordinary clients.
-- * Never grant client access to service-role/secret keys.
